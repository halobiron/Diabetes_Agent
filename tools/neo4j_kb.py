import json
from pathlib import Path

ENTITY_LABELS = {"Condition", "RiskFactor", "Test", "Intervention"}
RELATION_TYPES = {
    "INCREASES_RISK_OF",
    "DIAGNOSES",
    "REDUCES_RISK_OF",
    "ADDRESSES",
    "SHOULD_TEST_WITH",
}


class KnowledgeBaseError(ValueError):
    pass


def load_kb_file(path):
    with Path(path).open("r", encoding="utf-8") as file:
        return json.load(file)


def validate_kb(kb):
    """Check the KB file is internally consistent. Returns the KB; raises KnowledgeBaseError."""
    errors = []

    def ids_of(items, kind):
        ids = [item.get("id") for item in items]
        if len(ids) != len(set(ids)):
            errors.append(f"duplicate {kind} ids")
        return set(ids)

    source_ids = ids_of(kb.get("sources", []), "source")
    entity_ids = ids_of(kb.get("entities", []), "entity")
    evidence_ids = ids_of(kb.get("evidence", []), "evidence")

    for entity in kb.get("entities", []):
        if entity.get("label") not in ENTITY_LABELS:
            errors.append(f"entity {entity.get('id')}: unknown label {entity.get('label')}")
    for item in kb.get("evidence", []):
        if item.get("source") not in source_ids:
            errors.append(f"evidence {item['id']}: unknown source {item.get('source')}")
        if not item.get("text"):
            errors.append(f"evidence {item['id']}: empty text")
    for rel in kb.get("relations", []):
        name = f"{rel.get('from')}-{rel.get('type')}->{rel.get('to')}"
        if rel.get("type") not in RELATION_TYPES:
            errors.append(f"relation {name}: unknown type")
        for end in ("from", "to"):
            if rel.get(end) not in entity_ids:
                errors.append(f"relation {name}: unknown entity {rel.get(end)}")
        if not rel.get("evidence"):
            errors.append(f"relation {name}: no evidence")
        for evidence_id in rel.get("evidence", []):
            if evidence_id not in evidence_ids:
                errors.append(f"relation {name}: unknown evidence {evidence_id}")

    if errors:
        raise KnowledgeBaseError("; ".join(errors))
    return kb


def _cy(value):
    """Cypher literal for a str / int / None / list of str."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_cy(item) for item in value) + "]"
    text = " ".join(str(value).splitlines())
    text = text.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{text}'"


def to_cypher(kb):
    """The whole KB as one idempotent Cypher script (same graph as KnowledgeGraph.load).

    Run it with `cypher-shell -f kb_diabet.cypher` or paste it into Neo4j Browser.
    """
    validate_kb(kb)
    version = _cy(kb["version"])
    out = [
        f"// Diabetes knowledge graph - KB version {kb['version']}",
        f"// {len(kb['sources'])} sources, {len(kb['entities'])} entities, "
        f"{len(kb['evidence'])} evidence passages, {len(kb['relations'])} relations",
        "// Generated by scripts/export_kb_cypher.py from tests/fixtures/diabetes_kb.json; do not edit by hand.",
        "",
        "// --- Constraints ---",
    ]
    for label in ("Entity", "Evidence", "Source"):
        out.append(
            f"CREATE CONSTRAINT {label.lower()}_id IF NOT EXISTS FOR (n:{label}) REQUIRE n.id IS UNIQUE;"
        )

    out += ["", "// --- Sources ---"]
    for item in kb["sources"]:
        out.append(
            f"MERGE (s:Source {{id: {_cy(item['id'])}}}) SET s.title = {_cy(item.get('title'))}, "
            f"s.publisher = {_cy(item.get('publisher'))}, s.year = {_cy(item.get('year'))}, "
            f"s.url = {_cy(item.get('url'))}, s.kb_version = {version};"
        )

    out += ["", "// --- Entities (conditions, risk factors, tests, interventions) ---"]
    for item in kb["entities"]:
        key = f", n.key = {_cy(item['key'])}" if item.get("key") else ""
        out.append(
            f"MERGE (n:Entity {{id: {_cy(item['id'])}}}) SET n:{item['label']}, "
            f"n.name = {_cy(item['name'])}, n.description = {_cy(item.get('description'))}{key}, "
            f"n.kb_version = {version};"
        )

    out += ["", "// --- Evidence passages, each linked to its source ---"]
    for item in kb["evidence"]:
        out.append(
            f"MERGE (e:Evidence {{id: {_cy(item['id'])}}}) SET e.text = {_cy(item['text'])}, "
            f"e.section = {_cy(item.get('section'))}, e.kb_version = {version} "
            f"WITH e MATCH (s:Source {{id: {_cy(item['source'])}}}) "
            f"MERGE (e)-[f:FROM]->(s) SET f.kb_version = {version};"
        )

    out += ["", "// --- Relations between entities (each carries its evidence ids) ---"]
    for rel in kb["relations"]:
        out.append(
            f"MATCH (a:Entity {{id: {_cy(rel['from'])}}}), (b:Entity {{id: {_cy(rel['to'])}}}) "
            f"MERGE (a)-[r:{rel['type']}]->(b) "
            f"SET r.evidence_ids = {_cy(rel['evidence'])}, r.kb_version = {version};"
        )

    out += [
        "",
        "// --- Remove items left over from older KB versions ---",
        f"MATCH ()-[r]->() WHERE r.kb_version <> {version} DELETE r;",
        f"MATCH (n) WHERE (n:Entity OR n:Evidence OR n:Source) AND n.kb_version <> {version} DETACH DELETE n;",
        "",
    ]
    return "\n".join(out)


def create_driver(settings):
    from neo4j import GraphDatabase

    auth = (settings.neo4j_user, settings.neo4j_password) if settings.neo4j_password else None
    return GraphDatabase.driver(settings.neo4j_uri, auth=auth)


class KnowledgeGraph:
    """Diabetes knowledge graph stored in Neo4j. Takes a driver so tests can pass a fake."""

    def __init__(self, driver, database="neo4j"):
        self.driver = driver
        self.database = database

    def _run(self, query, **params):
        with self.driver.session(database=self.database) as session:
            return [record.data() for record in session.run(query, **params)]

    def ensure_schema(self):
        for label in ("Entity", "Evidence", "Source"):
            self._run(
                f"CREATE CONSTRAINT {label.lower()}_id IF NOT EXISTS "
                f"FOR (n:{label}) REQUIRE n.id IS UNIQUE"
            )

    def load(self, kb, prune=True):
        """Idempotent upsert of the whole KB; with prune, removes graph items no longer in the file."""
        validate_kb(kb)
        self.ensure_schema()
        version = kb["version"]

        self._run(
            "UNWIND $rows AS row MERGE (s:Source {id: row.id}) "
            "SET s.title = row.title, s.publisher = row.publisher, s.year = row.year, "
            "s.url = row.url, s.kb_version = $version",
            rows=kb["sources"],
            version=version,
        )
        for label in sorted({e["label"] for e in kb["entities"]}):
            rows = [e for e in kb["entities"] if e["label"] == label]
            self._run(
                "UNWIND $rows AS row MERGE (n:Entity {id: row.id}) "
                f"SET n:{label}, n.name = row.name, n.description = row.description, "
                "n.key = row.key, n.kb_version = $version",
                rows=rows,
                version=version,
            )
        self._run(
            "UNWIND $rows AS row MERGE (e:Evidence {id: row.id}) "
            "SET e.text = row.text, e.section = row.section, e.kb_version = $version "
            "WITH e, row MATCH (s:Source {id: row.source}) MERGE (e)-[f:FROM]->(s) SET f.kb_version = $version",
            rows=kb["evidence"],
            version=version,
        )
        for rel_type in sorted({r["type"] for r in kb["relations"]}):
            rows = [r for r in kb["relations"] if r["type"] == rel_type]
            self._run(
                "UNWIND $rows AS row "
                "MATCH (a:Entity {id: row.from}), (b:Entity {id: row.to}) "
                f"MERGE (a)-[r:{rel_type}]->(b) "
                "SET r.evidence_ids = row.evidence, r.kb_version = $version",
                rows=rows,
                version=version,
            )

        if prune:
            self.prune(version)

    def prune(self, version):
        self._run("MATCH ()-[r]->() WHERE r.kb_version <> $v DELETE r", v=version)
        self._run(
            "MATCH (n) WHERE (n:Entity OR n:Evidence OR n:Source) AND n.kb_version <> $v "
            "DETACH DELETE n",
            v=version,
        )

    def stats(self):
        return self._run(
            "MATCH (n) WHERE n:Entity OR n:Evidence OR n:Source "
            "WITH count(n) AS nodes "
            "OPTIONAL MATCH ()-[r]->() "
            "RETURN nodes, count(r) AS relationships"
        )[0]

    def all_evidence(self):
        """Every evidence passage with its source, the corpus the RetrievalAgent embeds."""
        return self._run(
            "MATCH (e:Evidence)-[:FROM]->(s:Source) "
            "RETURN e.id AS evidence_id, e.text AS text, e.section AS section, "
            "s.id AS source_id, s.title AS source_title, s.publisher AS publisher, "
            "s.year AS year, s.url AS url ORDER BY evidence_id"
        )

    def risk_factor_names(self):
        """Risk-factor key -> display name, e.g. {"BMI": "Overweight or obesity"}."""
        rows = self._run(
            "MATCH (f:RiskFactor) WHERE f.key IS NOT NULL RETURN f.key AS key, f.name AS name"
        )
        return {row["key"]: row["name"] for row in rows}

    def kb_version(self):
        rows = self._run("MATCH (s:Source) RETURN s.kb_version AS version LIMIT 1")
        return rows[0]["version"] if rows else None

    def relations_with_evidence(self, entity_id, limit=20):
        """Every relation touching the entity, each with its supporting evidence and source."""
        return self._run(
            "MATCH (a:Entity {id: $id})-[r]-(b:Entity) "
            "WITH a, r, b, startNode(r) = a AS outgoing "
            "UNWIND r.evidence_ids AS evidence_id "
            "MATCH (e:Evidence {id: evidence_id})-[:FROM]->(s:Source) "
            "RETURN type(r) AS relation, outgoing, b.id AS other_id, b.name AS other_name, "
            "e.id AS evidence_id, e.text AS evidence, e.section AS section, "
            "s.id AS source_id, s.title AS source_title, s.publisher AS publisher, "
            "s.year AS year, s.url AS url "
            "ORDER BY relation, other_name, evidence_id LIMIT $limit",
            id=entity_id,
            limit=limit,
        )

    def graph(self):
        """Whole graph for display: entities, relations (with evidence counts) and corpus sizes."""
        entities = self._run(
            "MATCH (n:Entity) RETURN n.id AS id, n.name AS name, n.description AS description, "
            "n.key AS key, [l IN labels(n) WHERE l <> 'Entity'][0] AS label ORDER BY label, name"
        )
        relations = self._run(
            "MATCH (a:Entity)-[r]->(b:Entity) RETURN a.id AS `from`, type(r) AS type, "
            "b.id AS `to`, size(r.evidence_ids) AS evidence_count ORDER BY `from`, type, `to`"
        )
        counts = self._run(
            "OPTIONAL MATCH (e:Evidence) WITH count(e) AS evidence "
            "OPTIONAL MATCH (s:Source) RETURN evidence, count(s) AS sources"
        )[0]
        return {
            "version": self.kb_version(),
            "entities": entities,
            "relations": relations,
            "evidence_count": counts["evidence"],
            "source_count": counts["sources"],
        }

    def support_for_risk_factors(self, factor_keys, limit=20):
        """Interventions and tests linked to risk factors (by model feature key), with evidence."""
        return self._run(
            "MATCH (f:RiskFactor) WHERE f.key IN $keys "
            "MATCH (x:Entity)-[r]-(f) WHERE (x:Intervention OR x:Test) "
            "AND type(r) IN ['ADDRESSES', 'SHOULD_TEST_WITH'] "
            "UNWIND r.evidence_ids AS evidence_id "
            "MATCH (e:Evidence {id: evidence_id})-[:FROM]->(s:Source) "
            "RETURN f.id AS risk_factor, f.key AS factor_key, x.id AS support_id, x.name AS support_name, "
            "labels(x) AS support_labels, type(r) AS relation, e.id AS evidence_id, "
            "e.text AS evidence, s.id AS source_id, s.title AS source_title, s.url AS url "
            "ORDER BY risk_factor, support_name LIMIT $limit",
            keys=list(factor_keys),
            limit=limit,
        )


class FileKnowledgeBase:
    """KnowledgeGraph read API backed by an explicit snapshot for offline tests and tools."""

    def __init__(self, kb):
        self.kb = validate_kb(kb)
        self._sources = {s["id"]: s for s in kb["sources"]}
        self._evidence = {e["id"]: e for e in kb["evidence"]}
        self._entities = {e["id"]: e for e in kb["entities"]}

    def _evidence_row(self, evidence_id):
        item = self._evidence[evidence_id]
        source = self._sources[item["source"]]
        return {
            "evidence_id": item["id"],
            "text": item["text"],
            "section": item.get("section"),
            "source_id": source["id"],
            "source_title": source["title"],
            "publisher": source.get("publisher"),
            "year": source.get("year"),
            "url": source.get("url"),
        }

    def all_evidence(self):
        return [self._evidence_row(evidence_id) for evidence_id in sorted(self._evidence)]

    def risk_factor_names(self):
        return {
            e["key"]: e["name"]
            for e in self._entities.values()
            if e["label"] == "RiskFactor" and e.get("key")
        }

    def kb_version(self):
        return self.kb["version"]

    def graph(self):
        return {
            "version": self.kb["version"],
            "entities": [
                {
                    "id": e["id"],
                    "name": e["name"],
                    "description": e.get("description"),
                    "key": e.get("key"),
                    "label": e["label"],
                }
                for e in sorted(self.kb["entities"], key=lambda e: (e["label"], e["name"]))
            ],
            "relations": [
                {
                    "from": r["from"],
                    "type": r["type"],
                    "to": r["to"],
                    "evidence_count": len(r.get("evidence", [])),
                }
                for r in self.kb["relations"]
            ],
            "evidence_count": len(self._evidence),
            "source_count": len(self._sources),
        }

    def relations_with_evidence(self, entity_id, limit=20):
        rows = []
        for rel in self.kb["relations"]:
            if entity_id not in (rel["from"], rel["to"]):
                continue
            outgoing = rel["from"] == entity_id
            other = self._entities[rel["to"] if outgoing else rel["from"]]
            for evidence_id in rel.get("evidence", []):
                row = self._evidence_row(evidence_id)
                rows.append(
                    {
                        "relation": rel["type"],
                        "outgoing": outgoing,
                        "other_id": other["id"],
                        "other_name": other["name"],
                        "evidence_id": evidence_id,
                        "evidence": row["text"],
                        "section": row["section"],
                        "source_id": row["source_id"],
                        "source_title": row["source_title"],
                        "publisher": row["publisher"],
                        "year": row["year"],
                        "url": row["url"],
                    }
                )
        rows.sort(key=lambda r: (r["relation"], r["other_name"], r["evidence_id"]))
        return rows[:limit]

    def support_for_risk_factors(self, factor_keys, limit=20):
        keys = set(factor_keys)
        factors = {e["id"]: e for e in self._entities.values() if e.get("key") in keys}
        rows = []
        for rel in self.kb["relations"]:
            if rel["type"] not in ("ADDRESSES", "SHOULD_TEST_WITH"):
                continue
            for factor_id, support_id in ((rel["from"], rel["to"]), (rel["to"], rel["from"])):
                support = self._entities[support_id]
                if factor_id not in factors or support["label"] not in ("Intervention", "Test"):
                    continue
                for evidence_id in rel["evidence"]:
                    row = self._evidence_row(evidence_id)
                    rows.append(
                        {
                            "risk_factor": factor_id,
                            "factor_key": factors[factor_id]["key"],
                            "support_id": support_id,
                            "support_name": support["name"],
                            "support_labels": ["Entity", support["label"]],
                            "relation": rel["type"],
                            "evidence_id": evidence_id,
                            "evidence": row["text"],
                            "source_id": row["source_id"],
                            "source_title": row["source_title"],
                            "url": row["url"],
                        }
                    )
        rows.sort(key=lambda r: (r["risk_factor"], r["support_name"]))
        return rows[:limit]
